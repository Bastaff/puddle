function migrate(db) {
  const cols = db.prepare(`PRAGMA table_info(events)`).all().map((c) => c.name);
  if (!cols.includes('source')) db.exec(`ALTER TABLE events ADD COLUMN source TEXT NOT NULL DEFAULT 'otel'`);
  if (!cols.includes('agent')) db.exec(`ALTER TABLE events ADD COLUMN agent TEXT NOT NULL DEFAULT 'claude-code'`);
  const pcols = db.prepare(`PRAGMA table_info(plan_limits)`).all().map((c) => c.name);
  if (pcols.length) for (const [c, t] of [['month_pct', 'REAL'], ['month_reset', 'INTEGER']]) if (!pcols.includes(c)) db.exec(`ALTER TABLE plan_limits ADD COLUMN ${c} ${t}`);
  const ucols = db.prepare(`PRAGMA table_info(users)`).all().map((c) => c.name);
  for (const c of ['name', 'country', 'timezone']) if (!ucols.includes(c)) db.exec(`ALTER TABLE users ADD COLUMN ${c} TEXT`);
  db.exec(`UPDATE events SET attrs_json = json_remove(attrs_json, '$.tool_parameters', '$.tool_input', '$.tool_output', '$.full_command', '$.error'),
      error = json_extract(attrs_json, '$.error_type')
    WHERE name IN ('tool_result', 'tool_decision') AND (json_extract(attrs_json, '$.tool_parameters') IS NOT NULL OR json_extract(attrs_json, '$.tool_input') IS NOT NULL OR json_extract(attrs_json, '$.error') IS NOT NULL)`);
  db.exec(`
    UPDATE OR IGNORE events SET dedupe = 'api:' || json_extract(attrs_json, '$.request_id')
      WHERE name = 'api_request' AND dedupe NOT LIKE 'api:%' AND json_extract(attrs_json, '$.request_id') IS NOT NULL;
    UPDATE OR IGNORE events SET dedupe = 'tr:' || json_extract(attrs_json, '$.tool_use_id')
      WHERE name = 'tool_result' AND dedupe NOT LIKE 'tr:%' AND json_extract(attrs_json, '$.tool_use_id') IS NOT NULL;
    UPDATE OR IGNORE events SET dedupe = 'td:' || json_extract(attrs_json, '$.tool_use_id')
      WHERE name = 'tool_decision' AND dedupe NOT LIKE 'td:%' AND json_extract(attrs_json, '$.tool_use_id') IS NOT NULL;
    UPDATE OR IGNORE events SET dedupe = 'up:' || json_extract(attrs_json, '$."prompt.id"')
      WHERE name = 'user_prompt' AND dedupe NOT LIKE 'up:%' AND json_extract(attrs_json, '$."prompt.id"') IS NOT NULL;
  `);
}

export function openDb(file, { rollup = false } = {}) {
  const db = new DatabaseSync(file);
  db.exec('PRAGMA journal_mode = WAL; PRAGMA synchronous = NORMAL;');
  db.exec(schema('sqlite').replace(/,\s*name TEXT, country TEXT, timezone TEXT/, '').replace(/,\s*source TEXT NOT NULL DEFAULT 'otel', agent TEXT NOT NULL DEFAULT 'claude-code'/, ''));
  migrate(db);
  db.exec('PRAGMA optimize=0x10002');
  const S = sqliteSql(db);
  const st = statements(S);
  const p = Object.fromEntries(Object.entries(st).map(([k, sql]) => [k, db.prepare(sql)]));

  const R = rollup ? sqliteRollup(db, S) : null;
  if (R && R.version() !== ROLLUP_VERSION) R.rebuild();
  function touch(identity, session, ts) {
    if (identity) p.upUser.run(...userArgs(identity, ts));
    if (session?.session_id) p.upSession.run(...sessionArgs(identity, session, ts));
  }
  function tx(fn) {
    db.exec('BEGIN');
    try { const r = fn(); db.exec('COMMIT'); return r; } catch (e) { db.exec('ROLLBACK'); throw e; }
  }

  return {
    db, sql: S, dialect: 'sqlite', rollup: { ready: () => Boolean(R) },
    upsertIdentity(id) {
      if (!id?.account_uuid && !id?.email) return;
      p.upIdentity.run(...identityArgs(id));
    },
    insertEvents(rows) {
      return tx(() => {
        let n = 0;
        const changed = [];
        for (const r of rows) {
          const was = R?.before(r.dedupe);
          touch(r.identity, r.session, r.ts);
          const c = Number(p.insEvent.run(...eventArgs(r)).changes);
          n += c;
          if (R && c) changed.push(was, { session_id: r.session?.session_id ?? null, user_key: r.identity?.key ?? null, ts: Math.round(r.ts) });
        }
        if (R) R.refresh(touchedKeys(changed));
        return n;
      });
    },
    insertPoints(points) {
      return tx(() => {
        let n = 0;
        for (const pt of points) {
          touch(pt.identity, pt.session, pt.ts);
          let value = pt.value;
          if (pt.cumulative) { value = cumulativeDelta(p.getState.get(pt.series_key), pt); p.setState.run(pt.series_key, pt.start_ns, pt.value); }
          if (value === 0) continue;
          p.insPoint.run(...pointArgs(pt, value));
          n++;
        }
        return n;
      });
    },
    addFeedback(fb) {
      if (!feedbackOk(fb)) return false;
      if (fb.verdict === 'undo') { db.prepare(`DELETE FROM flag_feedback WHERE user_key = ? AND kind = ?`).run(fb.user_key, fb.kind); return true; }
      db.prepare(`INSERT INTO flag_feedback (ts, user_key, kind, verdict, text) VALUES (?, ?, ?, ?, ?)`).run(Date.now(), fb.user_key, fb.kind, fb.verdict, String(fb.text || '').slice(0, 300));
      return true;
    },
    close() { db.close(); },
  };
}

async function inTx(pg, fn) {
  if (typeof pg.transaction === 'function') return pg.transaction((tx) => fn(pgSql(tx)));
  const client = await pg.connect();
  try { await client.query('BEGIN'); const r = await fn(pgSql(client)); await client.query('COMMIT'); return r; }
  catch (e) { await client.query('ROLLBACK').catch(() => {}); throw e; }
  finally { client.release(); }
}

